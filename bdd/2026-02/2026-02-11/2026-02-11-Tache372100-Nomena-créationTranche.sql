CREATE TABLE TRANCHE (
                         ID           VARCHAR2(50) PRIMARY KEY,
                         HEUREDEBUT   VARCHAR2(10),
                         HEUREFIN     VARCHAR2(10),
                         VAL          VARCHAR2(100),
                         DESCE        VARCHAR2(255)
);


CREATE SEQUENCE SEQ_TRANCHE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE NOCACHE NOORDER;

CREATE OR REPLACE FUNCTION get_SEQ_TRANCHE
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
SELECT SEQ_TRANCHE.NEXTVAL INTO retour FROM DUAL;

RETURN retour;
END;