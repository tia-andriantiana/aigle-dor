CREATE TABLE PIECEMACHINE (
      ID        VARCHAR2(250) NOT NULL,
      IDPIECE   VARCHAR2(250) NOT NULL,
      IDMACHINE VARCHAR2(250) NOT NULL,
      CONSTRAINT PK_PIECE_MACHINE PRIMARY KEY (ID),
      CONSTRAINT FK_PM_PIECE
          FOREIGN KEY (IDPIECE)
              REFERENCES AS_INGREDIENT_MAINTENANCE (ID),
      CONSTRAINT FK_PM_MACHINE
          FOREIGN KEY (IDMACHINE)
              REFERENCES AS_INGREDIENT_MAINTENANCE (ID)
);

CREATE SEQUENCE SEQ_PIECEMACHINE  INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;


CREATE OR REPLACE FUNCTION GET_SEQ_PIECEMACHINE
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
SELECT SEQ_PIECEMACHINE.NEXTVAL INTO retour FROM DUAL;

RETURN retour;
END;
