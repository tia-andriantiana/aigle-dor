CREATE OR REPLACE VIEW V_LIAISONPAIEMENT_VENTE AS
SELECT
    lp.ID ,
    lp.ID1 ,
    lp.ID2,
    lp.MONTANT,
    lp.ETAT,

    v.ID AS IDVENTE,
    v.DESIGNATION,
    v.IDMAGASIN,
    v.DATY,
    v.REMARQUE,
    v.ETAT AS ETATVENTE,
    v.IDCLIENT,
    v.MODEPAIEMENT,
    v.IDMODEPAIEMENT,
    v.NUMEROFACTURE,
    v.REFERENCEFACT,
    v.MONTANTDONNE,
    v.REMISE,
    v.REMISEMONTANT,
    v.DATEECHEANCE

FROM LIAISONPAIEMENT lp
JOIN VENTE v
    ON v.ID = lp.ID2
WHERE lp.ID2 LIKE 'VNT%';



CREATE OR REPLACE VIEW V_LIAISONPAIEMENT_FACTUREFOURN AS
SELECT
    lp.ID ,
    lp.ID1 ,
    lp.ID2,
    lp.MONTANT ,
    lp.ETAT ,

    f.ID AS IDFACTUREFOURNISSEUR,
    f.IDFOURNISSEUR,
    f.IDMODEPAIEMENT,
    f.DATY,
    f.DESIGNATION,
    f.ETAT AS ETATFACTURE,
    f.REFERENCE,
    f.IDBC,
    f.DEVISE,
    f.TAUX,
    f.IDMAGASIN,
    f.NUMERO,
    f.TYPEACHAT,
    f.ECHEANCEFACTURE

FROM LIAISONPAIEMENT lp
JOIN FACTUREFOURNISSEUR f
    ON f.ID = lp.ID2
WHERE lp.ID2 LIKE 'FCF%';

