CREATE TABLE AVOIRACHATFILLE (
     id VARCHAR2(255),
     idMere VARCHAR2(255) NOT NULL,
     idProduit VARCHAR2(255) NOT NULL,
     qte NUMBER(32, 2),
     pu NUMBER(32, 2),
     remise NUMBER(32, 2),
     tva NUMBER(32, 2),
     idDevise VARCHAR2(255) NOT NULL,
     taux NUMBER(32, 2),
     designation VARCHAR2(255),
     idFactureDetails VARCHAR2(255) NOT NULL
);

-- Ajout de la contrainte PRIMARY KEY
ALTER TABLE AVOIRACHATFILLE
