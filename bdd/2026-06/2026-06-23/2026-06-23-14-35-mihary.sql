-- Mere

CREATE SEQUENCE SEQ_AVOIRACHAT INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQ_AVOIRACHAT
  RETURN NUMBER
IS
  retour   NUMBER;
BEGIN
SELECT SEQ_AVOIRACHAT.NEXTVAL INTO retour FROM DUAL;
RETURN retour;
END;


CREATE TABLE AVOIRACHAT (
    id VARCHAR2(255),
    designation VARCHAR2(255),
    idmagasin VARCHAR2(255) NOT NULL,
    daty DATE,
    remarque VARCHAR2(255),
    etat NUMBER(32, 0),
    idfournisseur VARCHAR2(255) NOT NULL,
    idfacture VARCHAR2(255)
);

-- contrainte PRIMARY KEY
ALTER TABLE AVOIRACHAT
    ADD CONSTRAINT PK_AVOIRACHAT PRIMARY KEY (id);

-- contrainte FOREIGN KEY pour MAGASIN
ALTER TABLE AVOIRACHAT
    ADD CONSTRAINT FK_AVOIRACHAT_MAGASIN
        FOREIGN KEY (idmagasin)
            REFERENCES MAGASIN2(id);

-- contrainte FOREIGN KEY pour FOURNISSEUR
ALTER TABLE AVOIRACHAT
    ADD CONSTRAINT FK_AVOIRACHAT_FOURNISSEUR
        FOREIGN KEY (idfournisseur)
            REFERENCES FOURNISSEUR(id);

-- contrainte FOREIGN KEY pour FACTURE
ALTER TABLE AVOIRACHAT
    ADD CONSTRAINT FK_AVOIRACHAT_FACTURE
        FOREIGN KEY (idfacture)
            REFERENCES FACTUREFOURNISSEUR(id);

-- Fille

CREATE SEQUENCE SEQ_AVOIRACHATFILLE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQ_AVOIRACHATFILLE
