-- AvoirAchatLib

CREATE OR REPLACE VIEW avoirachatLib AS (
	SELECT a.*, m.id AS idmagasinLib, f.id AS idfournisseurLib
	FROM AVOIRACHAT a
	LEFT JOIN MAGASIN2 m ON a.IDMAGASIN = m.ID
	LEFT JOIN FOURNISSEUR f ON a.IDFOURNISSEUR = f.ID
);



-- AvoirAchatFilleLib

CREATE OR REPLACE VIEW avoirachatfillelib AS (
	SELECT af.*, p.id AS idproduitLib, d.id AS iddeviseLib
	FROM AVOIRACHATFILLE af
	LEFT JOIN PRODUIT p ON af.IDPRODUIT  = p.ID
	LEFT JOIN DEVISE d ON af.IDDEVISE = d.ID
);
