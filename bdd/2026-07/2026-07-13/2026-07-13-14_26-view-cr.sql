CREATE OR REPLACE VIEW VENTE_RECAP_JOUR
(
    DATY,
    MONTANTTTC,
    MONTANTPAYE,
    MONTANTRESTE,
    NOMBRE
) AS
SELECT
    TRUNC(DATY) AS DATY,
    CAST(SUM(NVL(MONTANTTTC, 0)) AS NUMBER(30,5)) AS MONTANTTTC,
    CAST(SUM(NVL(MONTANTPAYE, 0)) AS NUMBER(30,5)) AS MONTANTPAYE,
    CAST(SUM(NVL(MONTANTRESTE, 0)) AS NUMBER(30,5)) AS MONTANTRESTE,
    COUNT(*) AS NOMBRE
FROM VENTE_CPL
GROUP BY TRUNC(DATY);


CREATE OR REPLACE VIEW FACTUREFOURNISSEUR_RECAP_JOUR
(
    DATY,
    MONTANTTTC,
    MONTANTPAYE,
    MONTANTRESTE,
    NOMBRE
) AS
SELECT
    TRUNC(DATY) AS DATY,
    CAST(SUM(NVL(MONTANTTTC, 0)) AS NUMBER(30,5)) AS MONTANTTTC,
    CAST(SUM(NVL(MONTANTPAYE, 0)) AS NUMBER(30,5)) AS MONTANTPAYE,
    CAST(SUM(NVL(MONTANTRESTE, 0)) AS NUMBER(30,5)) AS MONTANTRESTE,
    COUNT(*) AS NOMBRE
FROM FACTUREFOURNISSEURCPL_TOUS_FAE,
WHERE IDTYPEFACTURE = 'TPF0002'
GROUP BY TRUNC(DATY);


CREATE OR REPLACE VIEW OFFILLESTOCK_RECAP_JOUR
(
    DATY,
    NOMBRE,
    QTE,
    QTEFABRIQUE,
    QTERESTE
) AS
SELECT
    TRUNC(DATY) AS DATY,
    COUNT(*) AS NOMBRE,
    CAST(SUM(NVL(QTE, 0)) AS NUMBER(30,5)) AS QTE,
    CAST(SUM(NVL(QTEFABRIQUE, 0)) AS NUMBER(30,5)) AS QTEFABRIQUE,
    CAST(SUM(NVL(QTERESTE, 0)) AS NUMBER(30,5)) AS QTERESTE
FROM OFFILLELIBSTOCK
GROUP BY TRUNC(DATY);