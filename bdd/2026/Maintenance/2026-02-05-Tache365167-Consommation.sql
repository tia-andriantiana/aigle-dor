CREATE TABLE CONSOMMATION (
    id VARCHAR(50) PRIMARY KEY,
    daty DATE,
    idTypeMaintenance VARCHAR(50),
    idMachine VARCHAR(50),
    desce VARCHAR(50),
    etat NUMBER(2),
    FOREIGN KEY (idTypeMaintenance) REFERENCES TYPEMAINTENANCE(ID),
    FOREIGN KEY (idMachine) REFERENCES AS_INGREDIENT_MAINTENANCE(ID)
);

CREATE SEQUENCE SEQ_CONSOMMATION INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQCONSOMMATION
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
SELECT SEQ_CONSOMMATION.nextval INTO retour FROM dual;
return retour;
END;

CREATE TABLE CONSOMMATIONDETAILS (
    id VARCHAR(50) PRIMARY KEY,
    idMere VARCHAR(50),
    idIngredients VARCHAR(50),
    qte NUMBER(30,5),
    idUnite VARCHAR(50),
    FOREIGN KEY (idMere) REFERENCES CONSOMMATION(ID),
    FOREIGN KEY (idIngredients) REFERENCES AS_INGREDIENTS(ID),
    FOREIGN KEY (idUnite) REFERENCES AS_UNITE(ID)
);

CREATE SEQUENCE SEQ_CONSOMMATIONDETAILS INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQCONSOMMATIONDETAILS
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
SELECT SEQ_CONSOMMATIONDETAILS.nextval INTO retour FROM dual;
return retour;
END;

CREATE OR REPLACE VIEW CONSOMMATIONLIB AS
SELECT
    c.*,
    tm.VAL AS idTypeMaintenanceLib,
    aim.LIBELLE AS idMachineLib
FROM CONSOMMATION c
         LEFT JOIN TYPEMAINTENANCE tm ON tm.ID = c.IDTYPEMAINTENANCE
         LEFT JOIN AS_INGREDIENT_MAINTENANCE aim ON aim.ID = c.IDMACHINE;

CREATE OR REPLACE VIEW CONSOMMATIONDETAILSLIB AS
SELECT
    c.*,
    au.VAL AS idUniteLib,
    ai.LIBELLE AS idIngredientsLib
FROM CONSOMMATIONDETAILS c
         LEFT JOIN AS_UNITE au ON au.ID = c.IDUNITE
         LEFT JOIN AS_INGREDIENTS ai ON ai.ID = c.IDINGREDIENTS;


CREATE OR REPLACE VIEW CONSOMMATIONLIB AS
SELECT
    c.*,
    tm.VAL AS idTypeMaintenanceLib,
    aim.LIBELLE AS idMachineLib,
    CASE
        WHEN c.ETAT = 1 THEN 'CR&Eacute;&Eacute;E'
        WHEN c.ETAT = 11 THEN 'VIS&Eacute;E'
        WHEN c.ETAT = 0 THEN 'ANNUL&Eacute;E'
