CREATE TABLE ReleveFab(
  ID VARCHAR(50) PRIMARY KEY NOT NULL,
  daty DATE,
  idfab VARCHAR(50),
  idReleve VARCHAR(50),
  etat NUMBER,
  FOREIGN KEY(idfab) REFERENCES fabrication(id),
  FOREIGN KEY(idReleve) REFERENCES compteurmaintenance(id)
);

CREATE SEQUENCE SEQRELEVEFAB INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION getseqrelevefab
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
SELECT SEQRELEVEFAB.NEXTVAL INTO retour FROM DUAL;
RETURN retour;
END;


