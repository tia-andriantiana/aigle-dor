CREATE TABLE CONSOMMABLEMACHINE (
    id VARCHAR(50) PRIMARY KEY,
    idMachine VARCHAR(50),
    idConsommable VARCHAR(50),
    idTypeMaintenance VARCHAR(50),
    qte NUMBER(30,5),
    idUnite VARCHAR(50),
    frequence VARCHAR(50),
    FOREIGN KEY (idTypeMaintenance) REFERENCES TYPEMAINTENANCE(ID),
    FOREIGN KEY (idConsommable) REFERENCES AS_INGREDIENTS(ID),
    FOREIGN KEY (idMachine) REFERENCES AS_INGREDIENT_MAINTENANCE(ID),
    FOREIGN KEY (idUnite) REFERENCES AS_UNITE(ID)
    FOREIGN KEY (frequence) REFERENCES UNITEMAINTENACE(ID)
);

CREATE SEQUENCE SEQ_CONSOMMABLEMACHINE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQCONSOMMABLEMACHINE
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
SELECT SEQ_CONSOMMABLEMACHINE.nextval INTO retour FROM dual;
return retour;
END;
