CREATE TABLE COMPTEURMAINTENANCE
(
    ID VARCHAR2(255) PRIMARY KEY NOT NULL,
    DATY DATE,
    IDLIGNE VARCHAR(255),
    VALEUR NUMBER(38,0),
    ECART NUMBER(38,0),
    FOREIGN KEY (IDLIGNE) REFERENCES LIGNE(ID)
);
CREATE SEQUENCE SEQCOMPTEURMAINTENANCE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER ;
CREATE OR REPLACE FUNCTION getSeqCompteurMaintenance
   RETURN NUMBER
	IS
	   retour   NUMBER;
BEGIN
SELECT SEQCOMPTEURMAINTENANCE.NEXTVAL INTO retour FROM DUAL;

RETURN retour;
END;

