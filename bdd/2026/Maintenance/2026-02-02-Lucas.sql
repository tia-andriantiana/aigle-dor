CREATE TABLE INTERDUREEPANNE 
   (	ID VARCHAR2(50) NOT NULL ENABLE, 
	IDMACHINE VARCHAR2(50), 
	DATEOT DATE, 
	DUREE NUMBER(*,0), 
	 PRIMARY KEY (ID),
	 CONSTRAINT FK_INTERDUREEPANNE_MACHINE FOREIGN KEY (IDMACHINE)
	  REFERENCES AS_INGREDIENT_MAINTENANCE (ID) 
   );

CREATE SEQUENCE SEQ_INTERDUREEPANNE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER 

CREATE OR REPLACE FUNCTION getseq_interdureepanne
   RETURN NUMBER
        IS
           retour   NUMBER;
        BEGIN
            SELECT seq_interdureepanne.NEXTVAL INTO retour FROM DUAL;
            
            RETURN retour;
        END;

CREATE OR REPLACE  VIEW ORDRETRAVAUXCPL (ID, LANCEPAR, CIBLE, REMARQUE, LIBELLE, BESOIN, DATY, ETAT, IDBC, TYPEMAINTENANCE) AS 
  (
	SELECT
		o.ID,o.LANCEPAR,o.CIBLE,o.REMARQUE,o.LIBELLE,o.BESOIN,o.DATY,o.ETAT,o.IDBC,
		p.idtypemaintenance AS typemaintenance
	FROM ORDRETRAVAUX o
	LEFT JOIN DEMANDETRAVAUX d ON d.id=o.idbc
	LEFT JOIN PLANNING p ON p.id=d.idplanning
);



CREATE OR REPLACE  VIEW MOYENNEPANNESTRAVAUX (IDMACHINE, NOMMACHINE, ECARTJOURS, IDENTITE) AS 
  SELECT
    idp.idMachine,
    ai.libelle AS nommachine,
    CAST(ROUND(AVG(idp.duree), 2) AS NUMBER(10,2)) AS ECARTJOURS,
    aim.identite
FROM interdureepanne idp
LEFT JOIN AS_INGREDIENT_MAINTENANCE aim 
       ON aim.id = idp.idmachine
LEFT JOIN AS_INGREDIENTS ai 
       ON ai.id = aim.idingredient
GROUP BY
    idp.idMachine,
    ai.libelle,
    aim.identite
;