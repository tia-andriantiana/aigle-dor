CREATE SEQUENCE seq_code_client
    MINVALUE 1
    MAXVALUE 999999999999999999999999999
    START WITH 1
    INCREMENT BY 1;

CREATE OR REPLACE FUNCTION GETSEQCODECLIENT
    RETURN VARCHAR2 IS
    retour NUMBER;
BEGIN
SELECT seq_code_client.NEXTVAL INTO retour FROM dual;
RETURN LPAD(retour, 5, '0');
END;