create or replace view AVOIRFCFILLELIB as
SELECT
    AF.ID,
    AF.IDAVOIRFC,
    AF.IDPRODUIT,
    AF.IDORIGINE,
    AF.QTE,
    AF.PU,
    AF.REMISE,
    AF.TVA,
    AF.PUACHAT,
    AF.PUVENTE,
    AF.IDDEVISE,
    AF.TAUXDECHANGE,
    AF.DESIGNATION,
    AF.IDVENTEDETAILS,
    P.libelle AS IDPRODUITLIB,
    P.CALORIE,
    P.CALORIE * AF.QTE AS POIDS,
    AF.PU * AF.QTE AS PTHT,
    (NVL(AF.pu,0) * NVL(AF.QTE,0)) * NVL(AF.TVA,0) / 100 AS montantTVA
FROM
    AVOIRFCFILLE AF
        LEFT JOIN as_ingredients P ON
        P.id = AF.IDPRODUIT