CREATE SEQUENCE seqPaiHS;

CREATE OR REPLACE FUNCTION getSeq_PaiementHS 
RETURN NUMBER 
IS 
    retour NUMBER;
BEGIN
    SELECT seqPaiHS.NEXTVAL
    INTO retour
    FROM DUAL;
    
    RETURN retour;
END;
 

CREATE OR REPLACE VIEW HS_NON_PAYE AS
SELECT *
FROM HEURESUPFABRICATION_CPL_VISEE hs
WHERE hs.ID NOT IN (
    SELECT IDHS 
    FROM PAIEMENTHEURESUP 
    WHERE IDHS IS NOT NULL
);