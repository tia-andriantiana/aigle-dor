CREATE OR REPLACE PROCEDURE DELETERESSOURCEFABRICATION (
    idFabrication IN VARCHAR2
)
AS
BEGIN
DELETE FROM RESSOURCEPARFABRICATION
WHERE IDFABRICATION = idFabrication;

COMMIT;
END;

CREATE OR REPLACE PROCEDURE DELETEHSFABRICATION (
    idFabrication IN VARCHAR2
)
AS
BEGIN
DELETE FROM HEURESUPFABRICATION
WHERE IDFABRICATION = idFabrication;

COMMIT;
END;


CREATE OR REPLACE VIEW HS_FABBRICATION_SEMAINECPL
AS
SELECT
    hs.*,
    pip.matricule,
    log.nom || ' ' || log.prenom as nomPersonnel,
    CAST(
            TRUNC(TO_DATE(SUBSTR(hs.SEMAINE, 1, 4) || '-01-04', 'YYYY-MM-DD'), 'IW')
                + (TO_NUMBER(SUBSTR(hs.SEMAINE, 6, 2)) - 1) * 7
        AS TIMESTAMP
    ) AS DEBUT_SEMAINE,
    CAST(
            TRUNC(TO_DATE(SUBSTR(hs.SEMAINE, 1, 4) || '-01-04', 'YYYY-MM-DD'), 'IW')
                + (TO_NUMBER(SUBSTR(hs.SEMAINE, 6, 2)) - 1) * 7
                + 6
        AS TIMESTAMP
    ) AS FIN_SEMAINE
FROM HS_FABRICATION_SEMAINE hs

         LEFT JOIN PAIE_INFO_PERSONNEL pip ON pip.id = hs.IDPERSONNE

         LEFT JOIN LOG_PERSONNEL log ON log.id = hs.IDPERSONNE;