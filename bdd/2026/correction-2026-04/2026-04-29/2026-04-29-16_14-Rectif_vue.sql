 CREATE OR REPLACE FORCE VIEW "FABRICATIONFILLECPL" AS
 SELECT
	f.ID,
	f.IDINGREDIENTS,
	f.LIBELLE,
	f.REMARQUE,
	f.IDMERE,
	f.DATYBESOIN,
	f.QTE,
	f.IDUNITE,
	f.PU,
	ai.LIBELLE AS idingredientsLib,
	p.NOM || ' - ' || p.TELEPHONE AS operateur,
	au.val AS IDUNITELIB,
	f.IDBCFILLE ,
	f.IDMACHINE,
	m.descriptionobjet AS IDMACHINELIB,
	ai.ISPETRI ,
	f2.IDOFFILLE 
FROM
	FABRICATIONFILLE f
JOIN FABRICATION f2 ON f2.ID = f.IDMERE 
LEFT JOIN AS_INGREDIENTS ai ON
	ai.id = f.IDINGREDIENTS
LEFT JOIN PERSONNEL p ON
	p.ID = f.OPERATEUR
LEFT JOIN AS_UNITE au ON
	au.id = f.IDUNITE
LEFT JOIN AS_INGREDIENT_MACHINE m ON m.ID = f.IDMACHINE  
;

CREATE OR REPLACE FORCE VIEW "OFRATTACHE" AS
SELECT 
    ofn."IDOFFILLE",
    ofn."DATY",
    ofn."IDPRODUIT",
    ofn."IDPRODUITLIB",
    ofn."QTE",
    ofn."QTEPETRI",
    ofn."IDLIGNE",
    ofn."LIGNE",
    r.IDRELEVE,
    -- Pourcentage de QTEPETRI par IDRELEVE
    (ofn."QTEPETRI" / SUM(ofn."QTEPETRI") OVER (PARTITION BY r.IDRELEVE)) * 100 AS POURCENTAGE
FROM ofnonrattache ofn
JOIN RELEVEFAB r 
    ON r.IDFAB = ofn."IDOFFILLE";