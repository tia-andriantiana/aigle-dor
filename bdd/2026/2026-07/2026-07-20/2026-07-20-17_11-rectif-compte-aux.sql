-- MAJ COMPTE G & COMPTE AUX COMPTA_SOUS_ECRITURE (COMPTE_AUX -> ID TIERS)
UPDATE COMPTA_SOUS_ECRITURE sse
SET (COMPTE, COMPTE_AUX) = (
    SELECT
        CASE WHEN u.ESTCLIENT = 1 THEN '411000' ELSE '401000' END,
        u.ID
    FROM (
        SELECT ID, COMPTE, 1 AS ESTCLIENT FROM CLIENT
        UNION ALL
        SELECT ID, COMPTE, 0 AS ESTCLIENT FROM FOURNISSEUR
    ) u
    WHERE u.COMPTE = sse.COMPTE
)
WHERE sse.COMPTE IN (
    SELECT COMPTE
    FROM (
        SELECT ID, COMPTE, 1 AS ESTCLIENT FROM CLIENT
        UNION ALL
        SELECT ID, COMPTE, 0 AS ESTCLIENT FROM FOURNISSEUR
    )
    WHERE COMPTE IS NOT NULL
    GROUP BY COMPTE
    HAVING COUNT(*) = 1
);

