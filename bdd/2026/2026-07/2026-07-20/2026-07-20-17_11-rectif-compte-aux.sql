    cse.DEBIT,
    cse.CREDIT,
    cse.REMARQUE,
    cse.LIBELLEPIECE,
    cse.IDMERE,
    cse.REFERENCE_ENGAGEMENT,
    t.COMPTEAUXILIAIRE AS COMPTE_AUX,
    cse.LETTRAGE,
    cse.JOURNAL,
    cse.EXERCICE,
    cse.ETAT,
    cse.DATY,
    cse.FOLIO,
    cse.ANALYTIQUE,
    cse.SOURCE
FROM COMPTA_SOUS_ECRITURE cse
LEFT JOIN TIERS t ON cse.COMPTE_AUX = t.ID;
