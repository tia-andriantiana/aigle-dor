create or replace view COMPTA_COMPTE_INGREDIENTS as
SELECT
    c."ID",c."COMPTE",c."LIBELLE",c."TYPECOMPTE",c."CLASSY",c."ANALYTIQUE_OBLI",c."IDJOURNAL",c."CODEIMPOT",
    si.ID AS idingredient,
    si.LIBELLE AS libelleIngredient
FROM COMPTA_COMPTE c
         LEFT JOIN ST_INGREDIENTSAUTOACHAT_CPL si ON c.COMPTE = si.COMPTE_ACHAT;

