CREATE TABLE SECTION (
    ID VARCHAR(255) PRIMARY KEY,
    IDSERVICE VARCHAR(255),
    VAL VARCHAR(255),
    DESCE VARCHAR(255),
    CONSTRAINT FK_SECTION_SERVICE
        FOREIGN KEY (IDSERVICE)
        REFERENCES SERVICE(ID)
);

CREATE SEQUENCE SEQ_SECTION INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER 

CREATE OR REPLACE FUNCTION GETSEQSECTION
	    RETURN NUMBER IS
	    retour NUMBER;
	BEGIN
	    SELECT SEQ_SECTION.nextval INTO retour FROM dual;
	    return retour;
	END;
 

CREATE OR REPLACE VIEW SECTIONLIB AS
SELECT 
    s.*,
    sv.LIBELLE AS idServiceLib
FROM SECTION s
LEFT JOIN SERVICE sv 
    ON s.IDSERVICE = sv.ID;