CREATE TABLE SOUSECRITUREDECLARER (
    ID VARCHAR2(255) PRIMARY KEY,
    IDSOUSECRITURE VARCHAR2(255) UNIQUE NOT NULL ,
    MOISDECLARATION NUMBER(2)
);

CREATE SEQUENCE SEQ_SousEcritureDeclarer INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION getSeqSousEcritureDeclarer
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
