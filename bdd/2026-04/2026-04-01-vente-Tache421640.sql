CREATE OR REPLACE  VIEW AS_INGREDIENT_VENTE_LIB (ID, LIBELLE, SEUIL, UNITE, QUANTITEPARPACK, PU, ACTIF, PHOTO, CALORIE, DURRE, COMPOSE, CATEGORIEINGREDIENT, IDFOURNISSEUR, DATY, QTELIMITE, PV, LIBELLEVENTE, SEUILMIN, SEUILMAX, PUACHATUSD, PUACHATEURO, PUACHATAUTREDEVISE, PUVENTEUSD, PUVENTEEURO, PUVENTEAUTREDEVISE, ISVENTE, ISACHAT, COMPTE_VENTE, COMPTE_ACHAT, LIBELLEEXTACTE, TVA, FILEPATH, RESTE, TYPESTOCK, REFPOST, REFQUALIFICATION, IDCHAMBRE, ISPERISHABLE, PV2, IDMAGASIN, PRIXUNITAIRE, IDTYPECLIENT, IDTYPECLIENTLIB, IDUNITE, IDUNITELIB, POIDS, QTE, TARIFMAGASIN) AS 
  select ing.ID,
       concat(concat(ing.LIBELLE, ' '), ing.PARFUMS) as LIBELLE,
       ing.SEUIL,
       ing.UNITE,
       ing.QUANTITEPARPACK,
       ing.PU,
       ing.ACTIF,
       ing.PHOTO,
       ing.CALORIE,
       ing.DURRE,
       ing.COMPOSE,
       ing.CATEGORIEINGREDIENT,
       ing.IDFOURNISSEUR,
       ing.DATY,
       ing.QTELIMITE,
       ing.PV,
       ing.LIBELLEVENTE,
       ing.SEUILMIN,
       ing.SEUILMAX,
       ing.PUACHATUSD,
       ing.PUACHATEURO,
       ing.PUACHATAUTREDEVISE,
       ing.PUVENTEUSD,
       ing.PUVENTEEURO,
       ing.PUVENTEAUTREDEVISE,
       ing.ISVENTE,
       ing.ISACHAT,
       ing.COMPTE_VENTE,
       ing.COMPTE_ACHAT,
       ing.LIBELLEEXTACTE,
       ing.TVA,
       ing.FILEPATH,
       ing.RESTE,
       ing.TYPESTOCK,
       ing.REFPOST,
       ing.REFQUALIFICATION,
       ing.IDCHAMBRE,
       ing.ISPERISHABLE,
       ing.PV2,
       ing.IDMAGASIN,
       nvl(ting.PRIXUNITAIRE,ing.PV) AS PRIXUNITAIRE,
       tc.ID as IDTYPECLIENT,
       tc.VAL as idtypeclientlib,
       nvl(un.id,un2.id) as idunite,
       nvl(un.VAL,un2.val) as idunitelib,
       eq.POIDS,
       eq.QUANTITE,
       ting.IDMAGASIN as TARIFMAGASIN
from AS_INGREDIENTS ing
         cross join TYPECLIENT tc
         left join TARIF_INGREDIENTS_MAX ting on ing.ID = TING.IDINGREDIENT AND ting.IDTYPECLIENT=tc.id
         left join AS_UNITE un on un.ID = TING.UNITE
         left join AS_UNITE un2 on un2.ID = ing.UNITE
         left join EQUIVALENCEVENTE eq on eq.IDPRODUIT2 = ting.IDINGREDIENT 
WHERE (ing.CATEGORIEINGREDIENT = 'CAT008' OR ing.ISVENTE = 1)
 ;

