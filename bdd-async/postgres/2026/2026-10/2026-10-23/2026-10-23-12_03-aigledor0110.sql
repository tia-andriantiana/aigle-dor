CREATE TABLE DEMANDE_PRIX
(
    ID          VARCHAR(250) NOT NULL PRIMARY KEY,
    DESIGNATION VARCHAR(500),
    DATY        DATE,
    ACHETEUR    VARCHAR(255),
    ETAT        INTEGER
);


CREATE SEQUENCE SEQ_DEMANDEPRIX
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999999999
    NO CYCLE
    CACHE 20;


CREATE OR REPLACE FUNCTION GET_SEQ_DEMANDEPRIX()
    RETURNS NUMERIC
    LANGUAGE plpgsql
AS $$
BEGIN
    RETURN nextval('seq_demandeprix');
END;
$$;


CREATE TABLE DEMANDE_PRIX_FILLE
(
    ID          VARCHAR(250) NOT NULL PRIMARY KEY,
    IDMERE      VARCHAR(250) NOT NULL,
    IDPRODUIT   VARCHAR(250) NOT NULL,
    DESIGNATION VARCHAR(255),
    QUANTITE    NUMERIC(30, 2),

    CONSTRAINT FK_DPF_MERE
        FOREIGN KEY (IDMERE)
            REFERENCES DEMANDE_PRIX(ID),

    CONSTRAINT FK_DP_PRODUIT
        FOREIGN KEY (IDPRODUIT)
            REFERENCES AS_INGREDIENTS(ID)
);


CREATE SEQUENCE SEQ_DEMANDE_PRIX_FILLE
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999999999
    NO CYCLE
    CACHE 20;


CREATE OR REPLACE FUNCTION GET_SEQ_DEMANDE_PRIX_FILLE()
    RETURNS NUMERIC
    LANGUAGE plpgsql
AS $$
BEGIN
    RETURN nextval('seq_demande_prix_fille');
END;
$$;


CREATE OR REPLACE VIEW DEMANDE_PRIX_FILLELIB AS
SELECT
    dpf.ID,
    dpf.IDMERE,
    dpf.IDPRODUIT,
    dpf.DESIGNATION,
    dpf.QUANTITE,
    ing.LIBELLE AS IDPRODUITLIB,
    ing.UNITE AS IDUNITELIB
FROM DEMANDE_PRIX_FILLE dpf
         LEFT JOIN AS_INGREDIENTS_LIB ing
                   ON ing.ID = dpf.IDPRODUIT;


CREATE OR REPLACE VIEW DEMANDE_PRIX_LIB AS
SELECT
    dp.ID,
    dp.DESIGNATION,
    dp.DATY,
    dp.ACHETEUR,
    dp.ETAT,
    CASE
        WHEN dp.ETAT = 1 THEN 'CRÉÉE'
        WHEN dp.ETAT = 0 THEN 'ANNULÉE'
        WHEN dp.ETAT = 11 THEN 'VISÉE'
        END AS ETATLIB
FROM DEMANDE_PRIX dp;




CREATE TABLE PROFORMA_ACHAT
(
    ID            VARCHAR(250) NOT NULL PRIMARY KEY,
    DESIGNATION   VARCHAR(255),
    DATY          DATE NOT NULL,
    IDFOURNISSEUR VARCHAR(250) NOT NULL,
    IDDEMANDEPRIX VARCHAR(250),
    ETAT          INTEGER,

    CONSTRAINT FK_PROFORMA_FRNS
        FOREIGN KEY (IDFOURNISSEUR)
            REFERENCES FOURNISSEUR(ID),

    CONSTRAINT FK_PROFORMA_DEMANDE
        FOREIGN KEY (IDDEMANDEPRIX)
            REFERENCES DEMANDE_PRIX(ID)
);


CREATE SEQUENCE SEQ_PROFORMA_ACHAT
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999999999
    NO CYCLE
    CACHE 20;


CREATE OR REPLACE FUNCTION GET_SEQ_PROFORMA_ACHAT()
    RETURNS NUMERIC
    LANGUAGE plpgsql
AS $$
BEGIN
    RETURN nextval('seq_proforma_achat');
END;
$$;


CREATE TABLE PROFORMA_ACHAT_FILLE
(
    ID              VARCHAR(250) NOT NULL PRIMARY KEY,
    IDMERE          VARCHAR(250) NOT NULL,
    IDPRODUIT       VARCHAR(250) NOT NULL,
    DESIGNATION     VARCHAR(500),
    DELAISLIVRAISON NUMERIC(10),
    PU              NUMERIC(38, 2),
    QTEDISPONIBLE   NUMERIC(19, 4),
    REMARQUE        VARCHAR(1000),

    CONSTRAINT FK_PAF_MERE
        FOREIGN KEY (IDMERE)
            REFERENCES PROFORMA_ACHAT(ID),

    CONSTRAINT FK_PROFORMA_DETAILS_PRODUIT
        FOREIGN KEY (IDPRODUIT)
            REFERENCES AS_INGREDIENTS(ID)
);


CREATE SEQUENCE SEQ_PROFORMA_ACHAT_FILLE
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 999999999999
    NO CYCLE
    CACHE 20;

CREATE OR REPLACE FUNCTION GET_SEQ_PROFORMA_ACHAT_FILLE()
    RETURNS NUMERIC
    LANGUAGE plpgsql
AS $$
BEGIN
    RETURN nextval('seq_proforma_achat_fille');
END;
$$;


CREATE OR REPLACE VIEW PROFORMA_ACHAT_FILLELIB AS
SELECT
    paf.ID,
    paf.IDMERE,
    paf.IDPRODUIT,
    paf.DESIGNATION,
    paf.DELAISLIVRAISON,
    paf.PU,
    paf.QTEDISPONIBLE,
    paf.REMARQUE,
    ing.LIBELLE AS IDPRODUITLIB,
    ing.UNITE AS IDUNITELIB,
    pa.DATY,
    pa.IDDEMANDEPRIX,
    pa.IDFOURNISSEUR,
    f.NOM AS IDFOURNISSEURLIB,
    COALESCE(paf.QTEDISPONIBLE, 0) * COALESCE(paf.PU, 0) AS MONTANT
FROM PROFORMA_ACHAT_FILLE paf
         LEFT JOIN AS_INGREDIENTS_LIB ing
                   ON ing.ID = paf.IDPRODUIT
         LEFT JOIN PROFORMA_ACHAT pa
                   ON pa.ID = paf.IDMERE
         LEFT JOIN FOURNISSEUR f
                   ON f.ID = pa.IDFOURNISSEUR;


CREATE OR REPLACE VIEW PROFORMA_ACHAT_LIB AS
SELECT
    pa.ID,
    pa.DESIGNATION,
    pa.DATY,
    pa.IDFOURNISSEUR,
    f.NOM AS IDFOURNISSEURLIB,
    pa.IDDEMANDEPRIX,
    pa.ETAT,
    CASE
        WHEN pa.ETAT = 1 THEN 'CRÉÉE'
        WHEN pa.ETAT = 0 THEN 'ANNULÉE'
        WHEN pa.ETAT = 11 THEN 'VISÉE'
        END AS ETATLIB
FROM PROFORMA_ACHAT pa
         LEFT JOIN FOURNISSEUR f
                   ON f.ID = pa.IDFOURNISSEUR;


