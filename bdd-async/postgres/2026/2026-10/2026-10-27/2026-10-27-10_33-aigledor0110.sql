alter table tarif_ingredients ADD COLUMN  puusd        numeric(30, 5);
alter table tarif_ingredients ADD COLUMN  pueuro       numeric(30, 5);

create or replace view tarif_ingredients_max (idingredient, unite, idtypeclient, prixunitaire, daty, idmagasin, puusd, pueuro) as
WITH ranked_tarifs AS (SELECT t.idingredient,
                              t.unite,
                              t.idtypeclient,
                              t.prixunitaire::numeric(30, 5)                                                                AS prixunitaire,
                              t.daty,
                              t.idmagasin,
                              t.puusd,
                              t.pueuro,
                              row_number()
                              OVER (PARTITION BY t.idingredient, t.unite, t.idtypeclient, t.idmagasin ORDER BY t.daty DESC) AS rn
                       FROM tarif_ingredients t)
SELECT r.idingredient,
       r.unite,
       r.idtypeclient,
       r.prixunitaire,
       r.daty,
       r.idmagasin,
       r.puusd,
       r.pueuro
FROM ranked_tarifs r
WHERE r.rn = 1;

CREATE OR REPLACE VIEW as_ingredient_vente_lib_stock AS
SELECT
    id,
    libelle,
    seuil,
    unite,
    quantiteparpack,
    pu,
    actif,
    photo,
    calorie,
    durre,
    compose,
    categorieingredient,
    idfournisseur,
    daty,
    qtelimite,
    pv,
    libellevente,
    seuilmin,
    seuilmax,
    puachatusd,
    puachateuro,
    puachatautredevise,
    puventeusd,
    puventeeuro,
    puventeautredevise,
    isvente,
    isachat,
    compte_vente,
    compte_achat,
    libelleextacte,
    tva,
    filepath,
    reste,
    typestock,
    refpost,
    refqualification,
    idchambre,
    isperishable,
    pv2,
    idmagasin,
    prixunitaire,
    idtypeclient,
    idtypeclientlib,
    idunite,
    idunitelib,
    poids,
    qte,
    tarifmagasin,
    quantite
FROM (
         SELECT
             ing.id,
             NULLIF(concat(ing.libelle, ' ', pointure.val, ' ', vrc.nomcouleur), ''::text) AS libelle,
             ing.seuil,
             ing.unite,
             ing.quantiteparpack,
             ing.pu,
             ing.actif,
             ing.photo,
             ing.calorie,
             ing.durre,
             ing.compose,
             ing.categorieingredient,
             ing.idfournisseur,
             ing.daty,
             ing.qtelimite,
             ing.pv,
             ing.libellevente,
             ing.seuilmin,
             ing.seuilmax,
             ing.puachatusd,
             ing.puachateuro,
             ing.puachatautredevise,
             CAST(COALESCE(ting.puusd, ing.puventeusd) AS NUMERIC(32, 2)) AS puventeusd,
             CAST(COALESCE(ting.pueuro, ing.puventeeuro) AS NUMERIC(32, 2)) AS puventeeuro,
             ing.puventeautredevise,
             ing.isvente,
             ing.isachat,
             ing.compte_vente,
             ing.compte_achat,
             ing.libelleextacte,
             ing.tva,
             ing.filepath,
             ing.reste,
             ing.typestock,
             ing.refpost,
             ing.refqualification,
             ing.idchambre,
             ing.isperishable,
             ing.pv2,
             v_e_ing.idmagasin,
             COALESCE(ting.prixunitaire, ing.pv) AS prixunitaire,
             tc.id AS idtypeclient,
             tc.val AS idtypeclientlib,
             COALESCE(un.id, un2.id) AS idunite,
             COALESCE(un.val, un2.val) AS idunitelib,
             eq.poids,
             eq.quantite AS qte,
             CAST(ting.idmagasin AS varchar(100)) AS tarifmagasin,
             v_e_ing.quantite
         FROM as_ingredients ing
                  CROSS JOIN typeclient tc
                    LEFT JOIN tarif_ingredients_max ting
                         ON ing.id = ting.idingredient
                             AND ting.idtypeclient = tc.id
                  LEFT JOIN as_unite un ON un.id = ting.unite
                  LEFT JOIN as_unite un2 ON un2.id = ing.unite
                  LEFT JOIN equivalencevente eq ON eq.idproduit2 = ting.idingredient
                  LEFT JOIN v_etatstock_ing v_e_ing ON v_e_ing.idproduit = ing.id
                  LEFT JOIN v_reference_couleur vrc ON ing.couleur::text = vrc.referencecouleur::text
                  LEFT JOIN pointure pointure ON ing.marque::text = pointure.id::text
         WHERE (ing.categorieingredient = 'CAT008' OR ing.isvente = 1)
           AND ing.actif = 1
     ) sub
;

