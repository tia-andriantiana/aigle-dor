CREATE OR REPLACE VIEW EVALUATION_ANNUELLE_LIB (ID, IDPERSONNEL, IDPERSONNELLIB, MATRICULE, IDFONCTION, IDFONCTIONLIB, ANNEE, NOTEGLOBALE, COMMENTAIRE, ETAT, ETATLIB) AS 
  SELECT
    ea.ID,
    ea.IDPERSONNEL,
