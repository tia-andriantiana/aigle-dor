CREATE OR REPLACE  VIEW "OFRATTACHE" ("ID", "IDOFFILLE", "DATY", "IDPRODUIT", "IDPRODUITLIB", "QTE", "QTEPETRI", "IDLIGNE", "LIGNE", "IDRELEVE", "POURCENTAGE") AS 
  SELECT 
  r.ID,
    ofn.IDOFFILLE,
    ofn.DATY,
    ofn.IDPRODUIT,
    ofn.IDPRODUITLIB,
    ofn.QTE,
    ofn.QTEPETRI,
    ofn.IDLIGNE,
    ofn.LIGNE,
    r.IDRELEVE,
    -- Pourcentage de QTEPETRI par IDRELEVE
    CAST((ofn.QTEPETRI / SUM(ofn.QTEPETRI) OVER (PARTITION BY r.IDRELEVE)) * 100 AS NUMBER(30,2) ) AS POURCENTAGE
FROM ofnonrattachereel ofn
JOIN RELEVEFAB r 
    ON r.IDFAB = ofn.IDOFFILLE;