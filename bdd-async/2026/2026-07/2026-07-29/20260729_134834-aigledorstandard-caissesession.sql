CREATE TABLE CAISSESESSION
(
    ID         VARCHAR2(255) NOT NULL PRIMARY KEY,

    IDCAISSE          VARCHAR2(255) NOT NULL REFERENCES CAISSE,

    DATEOUVERTURE     DATE NOT NULL,
    HEUREOUVERTURE    VARCHAR2(10),

    DATEFERMETURE     DATE,
    HEUREFERMETURE    VARCHAR2(10),

    IDUSEROUVERTURE   VARCHAR2(255) NOT NULL,
    IDUSERFERMETURE   VARCHAR2(255),

    ETAT              NUMBER
);


CREATE SEQUENCE seq_caissesession INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER

CREATE OR REPLACE FUNCTION GETSEQ_CAISSESSION
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
SELECT seq_caissesession.NEXTVAL INTO retour FROM DUAL;
RETURN retour;
END;









