    libelle varchar(255) ,
    idcategorie varchar(255) CONSTRAINT modele_categorie_fk REFERENCES CATEGORIEMODELE(id),
    idsousCategorie varchar(255) CONSTRAINT modele_souscat_fk REFERENCES SOUSCATEGORIEMODELE(id),
    univers varchar(255) CONSTRAINT modele_univers_fk REFERENCES UNIVERS(id),
    gamme varchar(255) CONSTRAINT modele_gamme_fk REFERENCES GAMME(id),
    statut varchar(255) CONSTRAINT modele_statut_fk REFERENCES STATUT(id),
    matiere varchar(255) CONSTRAINT modele_matiere_fk REFERENCES MATIERE(id),
    serie  varchar(255) CONSTRAINT modele_serie_fk REFERENCES SERIE(id), 
    collection varchar(255) CONSTRAINT modele_collection_fk REFERENCES COLLECTION(id),
    typologie varchar(255) CONSTRAINT modele_typologie_fk REFERENCES typologie(id),
    provenance varchar(255) CONSTRAINT modele_provenance_fk REFERENCES PROVENANCEMODELE(id),
    codeCouleur varchar(255) ,
    semelle varchar(255) CONSTRAINT modele_semelle_fk REFERENCES semelle(id)
);


create sequence seq_modele
      minvalue 1
      maxvalue 999999999999
      start with 1
      increment by 1
