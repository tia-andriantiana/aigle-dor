CREATE OR REPLACE VIEW V_PANIERMOYEN AS
SELECT
    DATY,
    IDPOINTLIB,
    IDPROVINCELIB,
    COUNT(*)                       AS QTE,         
    SUM(MONTANT_VENTE)             AS MONTANTTOTAL,
    SUM(MONTANT_VENTE) / COUNT(*)  AS PUTOTAL       
FROM (
    SELECT
        IDVENTE,
        DATY,
        IDPOINTLIB,
        IDPROVINCELIB,
        SUM(PUTOTAL) AS MONTANT_VENTE
    FROM VENTE_DETAILS_CPL_2_VISEE
    GROUP BY IDVENTE, DATY, IDPOINTLIB, IDPROVINCELIB
) VENTE_UNIQUE
GROUP BY DATY, IDPOINTLIB, IDPROVINCELIB;