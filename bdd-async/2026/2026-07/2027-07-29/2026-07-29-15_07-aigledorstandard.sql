CREATE SEQUENCE SEQ_typePointage INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQ_typePointage
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
SELECT SEQ_typePointage.NEXTVAL INTO retour FROM DUAL;
RETURN retour;
END;

CREATE TABLE POINTAGE_MAGASINIER (
	id varchar(255) PRIMARY KEY,
	idPoint varchar(255),
	idPersonnel varchar(255),
	idTypePointage varchar(255),
	daty DATE,
	heure varchar(255),
	remarque varchar(255),
	etat NUMBER (2),
	FOREIGN KEY (idPoint) REFERENCES point(id),
	FOREIGN KEY (idPersonnel) REFERENCES PAIE_INFO_PERSONNEL(id),
	FOREIGN KEY (idTypePointage) REFERENCES typePointage(id)
);

CREATE SEQUENCE SEQ_POINTAGE_MAGASINIER INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION GETSEQ_POINTAGE_MAGASINIER
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
SELECT SEQ_POINTAGE_MAGASINIER.NEXTVAL INTO retour FROM DUAL;
RETURN retour;
END;

CREATE VIEW POINTAGE_MAGASINIER_LIB (ID,IDPOINT,IDPOINTLIB,IDPERSONNEL,IDPERSONNELLIB,MATRICULEPERSONNEL,
IDTYPEPOINTAGE,IDTYPEPOINTAGELIB,DATY,HEURE,REMARQUE,ETAT,ETATLIB)
AS SELECT
pm.ID,
pm.IDPOINT,
P.VAL AS IDPOINTLIB,
pm.IDPERSONNEL,
LP.NOM || ' ' || LP.PRENOM AS IDPERSONNELLIB,
PIP.MATRICULE AS MATRICULEPERSONNEL,
pm.IDTYPEPOINTAGE,
TP.VAL AS IDTYPEPOINTAGELIB, 
pm.DATY,
pm.HEURE,
pm.REMARQUE,
pm.ETAT,
CASE 
	WHEN pm.etat = 1 THEN 'CREE'
	WHEN pm.etat = 11 THEN 'VALIDÉ'
END AS etatlib
FROM POINTAGE_MAGASINIER pm
LEFT JOIN POINT P ON P.ID = PM.IDPOINT
LEFT JOIN LOG_PERSONNEL LP ON LP.ID = PM.IDPERSONNEL
LEFT JOIN PAIE_INFO_PERSONNEL PIP ON PIP.ID = PM.IDPERSONNEL
LEFT JOIN TYPEPOINTAGE TP ON TP.ID = PM.IDTYPEPOINTAGE
