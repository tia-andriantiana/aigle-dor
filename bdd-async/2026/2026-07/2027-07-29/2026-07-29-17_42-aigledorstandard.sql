CREATE OR REPLACE VIEW V_PANIERMOYEN AS
SELECT
    DATY,
    IDPOINTLIB,
    IDPROVINCELIB,
    COUNT(*) AS QTE,
    SUM(MONTANTTOTAL_VENTE) AS MONTANTTOTAL,
    SUM(MONTANTTOTAL_VENTE) / COUNT(*) AS PUTOTAL
FROM (
    SELECT
        IDVENTE,
        DATY,
        IDPOINTLIB,
        IDPROVINCELIB,
        MAX(MONTANTTOTAL) AS MONTANTTOTAL_VENTE
    FROM VENTE_DETAILS_CPL_2_VISEE
    GROUP BY
        IDVENTE,
        DATY,
        IDPOINTLIB,
        IDPROVINCELIB
)
GROUP BY
    DATY,
    IDPOINTLIB,
    IDPROVINCELIB;