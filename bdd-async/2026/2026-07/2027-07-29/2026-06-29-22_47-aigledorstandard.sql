CREATE OR REPLACE VIEW CAISSESESSIONLIB AS
SELECT
cs.*,
pnt.val as idPointLib,
util.NOMUSER as IDUSEROUVERTURELIB,
util2.NOMUSER as IDUSERFERMETURELIB
FROM CAISSESESSION cs
LEFT JOIN Point pnt ON cs.idpoint = pnt.id
LEFT JOIN UTILISATEUR util ON util.refuser = cs.IDUSEROUVERTURE
LEFT JOIN UTILISATEUR util2 ON util2.refuser = cs.IDUSERFERMETURE