--MVTSTOCKAUTOCOMPLETE 

CREATE OR REPLACE  VIEW MVTSTOCKAUTOCOMPLETE (ID, DESIGNATION, IDMAGASIN, IDVENTE, IDTRANSFERT, IDTYPEMVSTOCK, DATY, ETAT, IDPOINT, IDOBJET, FABPRECEDENT, IDCATEGORIESTOCK,HEURE) AS 
  SELECT
m.ID,
m.DESIGNATION,
m.IDMAGASIN,
m.IDVENTE,
m.IDTRANSFERT,
m.IDTYPEMVSTOCK,
m.DATY,
m.ETAT,
m.IDPOINT,
m.IDOBJET,
CASE 
	WHEN m.FABPRECEDENT IS NOT NULL 
	THEN m.FABPRECEDENT||'---'||f.LIBELLE 
	ELSE m.FABPRECEDENT
END AS FABPRECEDENT,
m.IDCATEGORIESTOCK,
m.HEURE
FROM MVTSTOCK m 
LEFT JOIN FABRICATION f ON f.id = m.FABPRECEDENT;